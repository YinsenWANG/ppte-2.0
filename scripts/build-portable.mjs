import { build } from "esbuild";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
writeFileSync('packages/schema/src/version.ts', '// Generated from package.json by scripts/build-portable.mjs.\nexport const PPTE_APP_VERSION = ' + JSON.stringify(version) + ';\n');
const presenter = await build({entryPoints:["packages/editor-dom/src/presenter-window.ts"],bundle:true,write:false,platform:"browser",format:"iife",target:"es2022",minify:true});
writeFileSync("packages/editor-dom/src/presenter-window-bundle.ts", "// Generated by scripts/build-portable.mjs.\nexport const presenterWindowScript = " + JSON.stringify(presenter.outputFiles[0].text) + "\n");
const result = await build({
  entryPoints: ["packages/portable-runtime/src/browser.ts"],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "none",
});
writeFileSync(
  "packages/portable-runtime/src/browser-bundle.ts",
  "// Generated by scripts/build-portable.mjs; do not edit.\nexport const portableBrowserScript = " +
    JSON.stringify(result.outputFiles[0].text) +
    "\n",
);

mkdirSync('artifacts', { recursive: true });
const { createHash } = await import('node:crypto');
writeFileSync('artifacts/build-manifest.json', JSON.stringify({
  applicationVersion: version,
  runtimeBuildId: createHash('sha256').update(result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')).digest('hex'),
}, null, 2) + '\n');

import { chromium } from 'playwright';
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';
const audit=dirname(fileURLToPath(import.meta.url)), base=resolve('artifacts/independent-review');
await mkdir(base,{recursive:true});
const source=resolve(audit,'sample/source.html');
const original=resolve(audit,'sample/Cherry-Studio-开源之路.html');
const copy=base+'/editing-copy.html'; await copyFile(original,copy);
const cli=process.env.PPTE_CLI || resolve('artifacts/npm-package/ppte.js');
const child=spawn(process.execPath,[cli,'edit',copy,'--no-open','--port=0']);
const url=await new Promise((ok,no)=>{let text=''; child.stdout.on('data',c=>{text+=c;try{const r=JSON.parse(text.trim());r.ok?ok(r.url):no(Error(text))}catch{}});child.on('error',no);child.on('exit',c=>no(Error('server exit '+c)));});
const browser=await chromium.launch({channel:'chrome',headless:true});
const results={browser:browser.version(),viewport:{width:1280,height:800},rawPixelParity:[],errors:[],notes:[]};
const hash=b=>createHash('sha256').update(b).digest('hex');
try {
  const raw=await browser.newPage({viewport:results.viewport});
  const view=await browser.newPage({viewport:results.viewport});
  raw.setDefaultTimeout(10000); view.setDefaultTimeout(10000);
  await raw.goto(pathToFileURL(source).href); await view.goto(pathToFileURL(original).href);
  await view.waitForFunction(()=>!!window.PPTeSave&&!!window.PPTePlayer);
  const iframe=view.frameLocator('#ppte-frame');
  await view.screenshot({path:base+'/direct-file.png'});
  results.directFileControls=await view.evaluate(()=>({barDisplay:getComputedStyle(document.querySelector('#ppte-save-ui')).display,buttons:[...document.querySelectorAll('body>button')].map(n=>({text:n.textContent,opacity:getComputedStyle(n).opacity})),state:window.PPTeSave.state}));
  for(let i=0;i<12;i++){
    const a=await raw.locator('[data-ppte-slide]').nth(i).screenshot({path:base+`/raw-${i+1}.png`});
    const b=await iframe.locator('[data-ppte-slide]').nth(i).screenshot({path:base+`/slide-${i+1}.png`});
    results.rawPixelParity.push({page:i+1,identical:hash(a)===hash(b),rawHash:hash(a),enhancedHash:hash(b)});
  }
  results.layout=await view.evaluate(()=>[...window.PPTeHTML.contentDocument.querySelectorAll('[data-ppte-slide]')].map((s,i)=>{const r=s.getBoundingClientRect();return {page:i+1,width:r.width,height:r.height,overflow:[...s.querySelectorAll('h1,h2,h3,p,td,th')].filter(n=>{const q=n.getBoundingClientRect();return q.width&&q.height&&(q.bottom>r.bottom+1||q.top<r.top-1||q.right>r.right+1||q.left<r.left-1)}).map(n=>n.textContent)}}));
  const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(10000);
  page.on('pageerror',e=>results.errors.push(String(e)));
  await page.goto(url); await page.waitForFunction(()=>window.PPTeSave?.state==='saved'&&window.PPTeEditor);
  const frame=page.frameLocator('#ppte-frame');
  await page.screenshot({path:base+'/editor-initial.png'});
  const initial=await readFile(copy,'utf8');
  await page.getByRole('button',{name:'第 2 页',exact:true}).click();
  const paragraph=frame.locator('[data-ppte-slide]').nth(1).locator('p').nth(1);
  await paragraph.click();
  const targetId=await paragraph.getAttribute('data-ppte-id');
  const t0=performance.now();
  await paragraph.fill('验收修改：把注意力还给问题本身。');
  await page.waitForFunction(()=>window.PPTeSave.state==='saved'&&!window.PPTeSave.dirty);
  const saved=await readFile(copy,'utf8');
  assert.notEqual(hash(initial),hash(saved));assert(saved.includes('验收修改：把注意力还给问题本身。'));
  results.originalFileSave={confirmed:true,elapsedWithDebounceMs:performance.now()-t0,initialHash:hash(initial),savedHash:hash(saved)};
  await page.close();
  const reopened=await browser.newPage({viewport:{width:1440,height:1000}});
  reopened.setDefaultTimeout(10000);
  await reopened.goto(url);await reopened.waitForFunction(()=>window.PPTeSave?.state==='saved');
  assert.equal(await reopened.frameLocator('#ppte-frame').locator(`[data-ppte-id="${targetId}"]`).textContent(),'验收修改：把注意力还给问题本身。');
  results.originalFileSave.reopenConfirmed=true;
  await reopened.getByRole('button',{name:'第 1 页',exact:true}).click();
  await reopened.getByRole('button',{name:'放映',exact:true}).click();
  await reopened.waitForTimeout(2200);
  results.presentation=await reopened.evaluate(()=>({editable:window.PPTeHTML.contentDocument.querySelectorAll('[contenteditable="true"]').length,barDisplay:getComputedStyle(document.querySelector('#ppte-save-ui')).display,root:document.querySelector('#ppte-player')?.textContent}));
  await reopened.screenshot({path:base+'/present-cover.png'});
  await reopened.keyboard.press('b');await reopened.screenshot({path:base+'/blackout.png'});
  await reopened.keyboard.press('b');await reopened.keyboard.press('Escape');
  results.presentation.afterEscape=await reopened.evaluate(()=>({playerActive:window.PPTePlayer.active,workspace:document.querySelector('#ppte-workspace').hasAttribute('data-open')}));
  await reopened.getByRole('button',{name:'第 7 页',exact:true}).click();
  const table=reopened.frameLocator('#ppte-frame').locator('table');await table.locator('td').first().click();
  results.tableCellSelected=await reopened.locator('#ppte-properties h3').textContent();
  await reopened.screenshot({path:base+'/table-editor.png'});
  await reopened.getByRole('button',{name:'第 1 页',exact:true}).click();
  await reopened.getByRole('button',{name:'添加页',exact:true}).click();
  results.addPage=await reopened.evaluate(()=>{const doc=window.PPTeHTML.contentDocument; const all=[...doc.querySelectorAll('[data-ppte-slide]')];return {pages:all.length,last:all.at(-1).outerHTML,dimensions:all.map(n=>({width:n.getBoundingClientRect().width,height:n.getBoundingClientRect().height})),feedback:document.querySelector('#ppte-feedback').textContent}});
  await reopened.getByRole('button',{name:'第 13 页',exact:true}).click();await reopened.screenshot({path:base+'/added-page.png'});
  await reopened.waitForFunction(()=>window.PPTeSave.state==='saved');
  await reopened.close();
  const gallery=await browser.newPage({viewport:{width:1320,height:790}});
  await writeFile(base+'/contact.html',`<style>body{margin:0;background:#c8c7c2;display:grid;grid-template-columns:repeat(4,1fr);gap:12px;padding:12px}img{width:100%}</style>`+Array.from({length:12},(_,i)=>`<img src="slide-${i+1}.png">`).join(''));
  await gallery.goto(pathToFileURL(base+'/contact.html').href);await gallery.screenshot({path:base+'/contact.png',fullPage:true});
} catch(e){results.failure=String(e.stack);process.exitCode=1;} finally {await writeFile(base+'/result.json',JSON.stringify(results,null,2));await browser.close();child.kill('SIGTERM');}
console.log(JSON.stringify(results,null,2));
